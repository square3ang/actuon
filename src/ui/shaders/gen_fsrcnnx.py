#!/usr/bin/env python3
"""Turns FSRCNNX's mpv shader into plain WGSL fragment shaders. Run it when the model changes."""
import pathlib
import re

here = pathlib.Path(__file__).parent
src = (here / "../../../third_party/fsrcnnx/FSRCNNX_x2_8-0-4-1.glsl").read_text()
passes = re.split(r"(?=^//!HOOK )", src, flags=re.M)[1:]
HEADER = """// Generated by gen_fsrcnnx.py from FSRCNNX (LGPL 3, see third_party/fsrcnnx).
fn fetch(t: texture_2d<f32>, p: vec2i, o: vec2i) -> vec4f {
    return textureLoad(t, clamp(p + o, vec2i(0), vec2i(textureDimensions(t)) - 1), 0);
}
"""


def to_wgsl(body):
    """Rewrites one pass's hook() body. mpv's offsets are whole texels: a bare 0 means no offset."""
    body = re.sub(r"float\(LUMA_texOff\(vec2\((-?\d+),(-?\d+)\)\)\)", r"dot(fetch(LUMA, p, vec2i(\1,\2)).rgb, vec3f(0.2126, 0.7152, 0.0722))", body)
    body = re.sub(r"(\w+)_texOff\(vec2\((-?\d+),(-?\d+)\)\)", r"fetch(\1, p, vec2i(\2,\3))", body)
    body = re.sub(r"(\w+)_texOff\(0\)", r"fetch(\1, p, vec2i(0))", body)
    body = re.sub(r"\bvec4 res =", "var res =", body)
    body = re.sub(r"\bmat4(x4)?\(", "mat4x4f(", body)
    return re.sub(r"\bvec4\(", "vec4f(", body)


for f in here.glob("fsrcnnx_[0-9]*.frag.wgsl"):
    f.unlink()
# The last pass only unpacks channels into pixels, so it is written by hand: see fsrcnnx_unpack.
for i, text in enumerate(passes[:-1]):
    binds = re.findall(r"^//!BIND (\w+)$", text, flags=re.M)
    saved = re.search(r"^//!SAVE (\w+)$", text, flags=re.M).group(1)
    out = HEADER
    for b, name in enumerate(binds):
        out += f"@group(1) @binding({b}) var {name}: texture_2d<f32>;\n"
    start = text.index("{", text.index("vec4 hook()")) + 1
    body = text[start : text.rindex("}")]
    out += "@fragment fn main(@builtin(position) pos: vec4f) -> @location(0) vec4f {\nlet p = vec2i(pos.xy);" + to_wgsl(body) + "}\n"
    (here / f"fsrcnnx_{i}.frag.wgsl").write_text(out)
    print(i, binds, "->", saved)
