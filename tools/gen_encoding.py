#!/usr/bin/env python3
def table(codec, lead_lo, lead_hi, trail_lo, trail_hi):
    out = []
    for lead in range(lead_lo, lead_hi + 1):
        for trail in range(trail_lo, trail_hi + 1):
            try:
                s = bytes([lead, trail]).decode(codec)
                out.append(ord(s) if len(s) == 1 and ord(s) < 0x10000 else 0)
            except UnicodeDecodeError:
                out.append(0)
    return out

def emit(f, name, values):
    f.write(f"pub const {name} = [_]u16{{\n")
    for i in range(0, len(values), 24):
        f.write(",".join(str(v) for v in values[i:i + 24]) + ",\n")
    f.write("};\n")

with open("src/bms/enc_tables.zig", "w") as f:
    f.write("// Generated by tools/gen_encoding.py. Do not edit.\n")
    emit(f, "cp932", table("cp932", 0x81, 0xFC, 0x40, 0xFC))
    emit(f, "cp949", table("cp949", 0x81, 0xFE, 0x41, 0xFE))
